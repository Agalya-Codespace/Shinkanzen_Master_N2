def pick(id, q, opts, ans, explain):
    return mcq(id, q, opts, ans, explain, keys=[""] * len(opts))

def W(*xs):
    """Accept half-width and full-width digits/letters."""
    out = []
    for x in xs:
        out.append(x)
        fw = x.translate(str.maketrans("0123456789ABCDP", "０１２３４５６７８９ＡＢＣＤＰ"))
        if fw != x: out.append(fw)
    return out

