def suru_group(n, rows):
    """第45回 Ⅲ: the underlined kanji is half of a 「○○する」 word; type the other kanji, then the reading."""
    ch = []
    for i, (q, kanji, yomi, ex) in enumerate(rows):
        ch.append(fill("d%dk-%d-3%d" % (DAY, n, i + 1), NUMS[i] + q + "　□＝%%", kanji, ex))
        ch.append(fill("d%dk-%d-3%dy" % (DAY, n, i + 1), "　↳ 読み方：%%", yomi))
