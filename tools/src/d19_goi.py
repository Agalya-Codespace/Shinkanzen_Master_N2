def parse(s):
    out = []
    for w in s.split("・"):
        w = w.strip()
        if "|" in w:
            k, y = w.split("|")
            out.append((k, y))
        else:
            out.append((w, w))
    return out

def ruby(k, y):
    if k == y: return k
    # keep katakana / kana part outside the ruby
    i = 0
    while i < len(k) and i < len(y) and k[i] == y[i]: i += 1
    j = 0
    while j < len(k) - i and j < len(y) - i and k[-1 - j] == y[-1 - j]: j += 1
    head, tail = k[:i], k[len(k) - j:] if j else ""
    core_k, core_y = k[i:len(k) - j], y[i:len(y) - j]
    return head + ("{%s|%s}" % (core_k, core_y) if core_k else "") + tail

WL1 = []
def K(suf, words, ex):
    ws = parse(words)
    WL1.append((suf, ws))
    return L("**%s**　%s" % (suf, "・".join(ruby(k, y) for k, y in ws)), ex)

